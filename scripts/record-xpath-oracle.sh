#!/usr/bin/env bash
# Builds tests/xpath/oracle.xsl from tests/xpath/expressions.txt and records
# xsltproc's results on tests/xpath/doc.xml as tests/xpath/expected.txt,
# in the reference container so the libxml2 version is fixed.
#
#   scripts/record-xpath-oracle.sh
#
# For each expression the output has an entry:
#   [n] <expression>
#   = <string(expression)>
#   nodes: <name()>/<string-length(.)> ...    (only for lines starting "n ")
# tests/xpath_oracle.rs prints the same from oxslt's evaluator.

set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
dir=$here/tests/xpath
image=oxslt-reference

python3 -I - "$dir/expressions.txt" "$dir/oracle.xsl" <<'EOF'
import sys
src, out = sys.argv[1], sys.argv[2]
def attr(s): return s.replace("&", "&amp;").replace("<", "&lt;").replace('"', "&quot;")
def text(s): return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
body = []
k = 0
for line in open(src, encoding="utf-8"):
    line = line.rstrip("\n")
    if not line.strip() or line.lstrip().startswith("#"):
        continue
    k += 1
    nodes = line.startswith("n ")
    expr = line[2:] if nodes else line
    body.append(f'<xsl:text>[{k}] {text(expr)}&#10;= </xsl:text><xsl:value-of select="string({attr(expr)})"/>')
    if nodes:
        body.append(f'<xsl:text>&#10;nodes:</xsl:text><xsl:for-each select="{attr(expr)}">'
                    '<xsl:text> </xsl:text><xsl:value-of select="name()"/><xsl:text>/</xsl:text>'
                    '<xsl:value-of select="string-length(string(.))"/></xsl:for-each>')
    body.append('<xsl:text>&#10;</xsl:text>')
with open(out, "w", encoding="utf-8") as f:
    f.write('<?xml version="1.0"?>\n<!-- Generated by scripts/record-xpath-oracle.sh from expressions.txt. -->\n')
    f.write('<xsl:stylesheet version="1.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform"\n'
            '  xmlns:a="urn:a" xmlns:c="urn:c" xmlns:d="urn:default">\n'
            '<xsl:output method="text" encoding="UTF-8"/>\n<xsl:template match="/">\n')
    f.write("\n".join(body))
    f.write('\n</xsl:template>\n</xsl:stylesheet>\n')
print(f"{k} expressions")
EOF

docker image inspect "$image" >/dev/null 2>&1 || docker build --platform linux/amd64 -t "$image" "$here/tests/reference"
docker run --rm --platform linux/amd64 --network none --read-only -v "$dir":/x "$image" \
  sh -c 'cd /x && xsltproc oracle.xsl doc.xml > expected.txt' 2>&1 | grep -v 'WARNING: The requested image' || true
echo "recorded $(grep -c '^\[' "$dir/expected.txt") entries in tests/xpath/expected.txt"

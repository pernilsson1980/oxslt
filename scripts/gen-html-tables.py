#!/usr/bin/env python3
"""Generates src/html/tables.rs from libxml2 2.9.14's HTMLparser.c.

    scripts/gen-html-tables.py path/to/HTMLparser.c > src/html/tables.rs
"""
import re
import sys

src = open(sys.argv[1], encoding="latin-1").read()

def section(start, end):
    i = src.index(start)
    return src[i:src.index(end, i)]

elements = re.findall(
    r'\{\s*"(\w+)",\s*(\d),\s*(\d),\s*(\d),\s*(\d),\s*(\d),\s*(\d),\s*(\d),',
    section("html40ElementTable[] = {", "\n};"))
pairs = re.findall(r'\{\s*"(\w+)",\s*"(\w+)"\s*\}',
                   section("htmlStartClose[] = {", "\n};"))
entities = re.findall(r'\{\s*(\d+),\s*"(\w+)",',
                      section("html40EntitiesTable[] = {", "\n};"))
assert len(elements) > 90 and len(pairs) > 200 and len(entities) > 250

print("// Generated by scripts/gen-html-tables.py from libxml2 2.9.14's")
print("// HTMLparser.c. Don't edit by hand.")
print()
print("/// html40ElementTable: (name, start tag omissible, end tag (0 required,")
print("/// 1 omissible, 2 forbidden, 3 stylistic), empty), sorted by name.")
print("pub(super) const ELEMENTS: &[(&str, u8, u8, bool)] = &[")
for name, start, end, save, empty, *_ in sorted(elements, key=lambda e: e[0]):
    print(f'    ("{name}", {start}, {end}, {"true" if empty == "1" else "false"}),')
print("];")
print()
print("/// htmlStartClose: (open element, start tag that closes it), sorted.")
print("pub(super) const START_CLOSE: &[(&str, &str)] = &[")
for old, new in sorted(pairs):
    print(f'    ("{old}", "{new}"),')
print("];")
print()
print("/// html40EntitiesTable: (name, code point), in the table's order.")
print("pub(super) const ENTITIES: &[(&str, u32)] = &[")
for value, name in entities:
    print(f'    ("{name}", {value}),')
print("];")
